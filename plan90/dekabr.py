REZERV = {"подарочный сертификат спа", "йога для начинающих", "зумба что это", "бокс для начинающих"}   # ждут ответа клуба


def wordstat():
    W = {}
    for r in ("35", "1058", "225"):
        W[r] = {}
        for p, dt in (("k", "10.11.2026"), ("k2", "10.11.2026"), ("dek", "17.11.2026"), ("dek2", "17.11.2026")):
            f = ROOT / "semantika" / f"{p}-{r}.json"
            if f.exists():
                for k, v in json.loads(f.read_text()).items():
                    if isinstance(v, dict) and "err" not in v:
                        W[r][k] = dict(v, dt=dt)
    H = {}
    for r in ("35", "1058", "225"):
        f = ROOT / "semantika" / f"dek-istoriya-{r}.json"
        if f.exists():
            for k, v in json.loads(f.read_text()).items():
                H.setdefault(k, {})[r] = dict(v.get("mes") or []).get("декабрь 2025")
    return W, H


def vedyot90(club, key):
    k = key.lower()
    if re.search(r"массаж|чистк|эпиляц|маникюр|педикюр|солярий|спа|лица|кожей", k):
        return "Balance спа" if club == "imp" else "массажный кабинет Абрикосово" if club == "abr" else "Balance Адмирал"
    if re.search(r"плаван|бассейн|дышать", k): return {"abr": "бассейн Абрикосово", "imp": "бассейн Империала", "adm": "бассейн Адмирала"}[club]
    if re.search(r"ребен|детск|подрост|осанка у", k): return f"Детский клуб Balance, {KLUB[club][1]}"
    if re.search(r"белк|калори|вод|протеин|питани|креатин", k) and club == "abr": return "Balance кафе Абрикосово (КБЖУ блюд)"
    if re.search(r"пилатес|диастаз|родов|фитбол", k): return "студия пилатеса и реформер" + (" Абрикосово" if club == "abr" else " Адмирала")
    if re.search(r"солян|сауна|контрастн", k): return {"abr": "бани Абрикосово", "imp": "акватермальная зона Империала", "adm": "сауны и хаммам Адмирала"}[club]
    return {"abr": "тренажёрный зал Абрикосово, вводная тренировка", "imp": "тренажёрный зал Империала, вводная тренировка",
            "adm": "тренажёрный зал Адмирала, вводная тренировка"}[club]


def main():
    W, H = wordstat()
    vyshlo = set()
    for md in (ROOT / "stati").glob("*.md"):
        m = re.search(r"^query:\s*(.+)$", md.read_text(encoding="utf8"), re.M)
        if m: vyshlo.add(m.group(1).strip().lower())
    po_klubu = {c: [] for c in KLUB}
    for c in KLUB:
        ostatok = [dict(x, pin=None, vedyot=vedyot90(c, x["key"]), istochnik="plan90")
                   for x in T if x["club"] == c and x["key"] not in REZERV and x["key"].lower() not in vyshlo]
        for x in ostatok:
            if x["key"] in PIN90: x["pin"] = date(2026, int(PIN90[x["key"]][3:5]), int(PIN90[x["key"]][:2]))
        novye = [dict(x, istochnik="spros-dekabr") for x in N if x["club"] == c]
        sloty = {}
        for x in [x for x in novye + ostatok if x["pin"]]:
            assert x["pin"] not in sloty, f"{c}: две темы на {x['pin']}"
            sloty[x["pin"]] = x
        svobodnye = iter([x for x in ostatok if not x["pin"]])
        for d in DATY:
            if d not in sloty: sloty[d] = next(svobodnye)
        lishnie = list(svobodnye)
        assert not lishnie, f"{c}: не влезли {[x['key'] for x in lishnie]}"
        po_klubu[c] = [(d, sloty[d]) for d in DATY]
    plan, err = [], []
    for d in DATY:
        for c, (slug, imya, gorod) in KLUB.items():
            x = dict(po_klubu[c][DATY.index(d)][1])
            k = x["key"]
            rf, krd, tua = (W[r].get(k, {}).get("total") for r in ("225", "35", "1058"))
            dt = next((W[r][k]["dt"] for r in ("225", "35", "1058") if k in W[r]), None)
            pop = (W["225"].get(k) or W["35"].get(k) or {}).get("popular") or []
            dop = [t for t, _ in pop if t != k and not NOISE.search(t)][:5]
            gl = tua if c == "adm" else krd
            ch = lambda v: f"{v or 0:,}".replace(",", " ")
            if rf or gl:
                spros = (f"{ch(gl)} в месяц – {'Туапсе' if c == 'adm' else 'Краснодарский край'}, {ch(rf)} – Россия, Wordstat {dt}"
                         if gl else f"{ch(rf)} в месяц по России (в {'Туапсе' if c == 'adm' else 'крае'} не набирается), Wordstat {dt}")
            else:
                spros = "частота не снималась в нужной форме: тема взята " + ("под зону клуба" if x["flag"] else "по сезону")
            dek = H.get(k, {})
            if dek.get("35") or dek.get("225"):
                spros += f"; декабрь 2025 – {dek.get('35') or 0} в крае, {dek.get('225') or 0} по России"
            plan.append(dict(data=d.isoformat(), klub=slug, key=k, title=x["title"], intent=x["intent"], angle=x["angle"],
                             aeo=x["aeo"], vedyot=x["vedyot"], vedyot_url=URL.format(slug), dop_klyuchi=dop,
                             spros=spros, flag=x["flag"], istochnik=x["istochnik"]))
    # проверки
    if len(plan) != 117: err.append(f"строк {len(plan)}, нужно 117")
    for d in DATY:
        kl = sorted(p["klub"] for p in plan if p["data"] == d.isoformat())
        if kl != sorted(v[0] for v in KLUB.values()): err.append(f"{d}: клубы {kl}")
    keys = [p["key"] for p in plan]
    for k in sorted({k for k in keys if keys.count(k) > 1}): err.append(f"ключ дважды: {k}")
    for k in keys:
        if k.lower() in vyshlo: err.append(f"ключ уже есть в вышедших статьях: {k}")
    out = ROOT / "plan90"
    (out / "dekabr.json").write_text(json.dumps(dict(sozdan="2026-11-17", rezerv=sorted(REZERV), plan=plan), ensure_ascii=False, indent=1) + "\n")
    md = ["# План статей сайта Баланса 23.11–31.12.2026 (3 в день)", "",
          f"Строк {len(plan)}: из plan90 – {sum(p['istochnik'] == 'plan90' for p in plan)}, новых по спросу – "
          f"{sum(p['istochnik'] == 'spros-dekabr' for p in plan)}. Резерв до ответа клуба: {', '.join(sorted(REZERV))}.", "",
          "| Дата | Клуб | Главный ключ | Заголовок | Спрос | Ведём на | ⚠ |", "|---|---|---|---|---|---|---|"]
    for p in plan:
        md.append(f"| {p['data'][8:]}.{p['data'][5:7]} | {p['klub']} | {p['key']} | {p['title']} | {p['spros']} | {p['vedyot']} | {p['flag']} |")
    (out / "dekabr.md").write_text("\n".join(md) + "\n")
    for e in err: print("ОШИБКА", e)
    print(f"план: {len(plan)} строк, ошибок {len(err)}")
    return 1 if err else 0


if __name__ == "__main__":
    sys.exit(main())
